"""A catalogue of realistic bad changes to the source of truth (Slice 2: "bugs caught / injected").

Each mutation is a mistake an engineer could make in a PR. The static gates (SoT validation, golden
render, capacity what-if, redundancy rule) must reject it; the ones only a live network can reveal are
marked `twin` and are caught by the temporary twin in CI (tests_live), see results/bad-changes.md.

    python tests/bad_changes.py   -> prints the scoreboard and writes results/bad-changes.md
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from netgen import model, whatif  # noqa: E402


def m_overlap(s):
    s["links"]["L23"]["subnet"] = s["links"]["L12"]["subnet"]


def m_unknown_fibre(s):
    s["links"]["L34"]["fibres"] = ["F43"]                       # typo


def m_broken_lightpath(s):
    s["links"]["L13"]["fibres"] = ["F12", "F34"]                # route has a gap


def m_wrong_end(s):
    s["links"]["L13"]["fibres"] = ["F12"]                       # lightpath stops at r2, link ends at r3


def m_duplicate_iface(s):
    s["customers"]["h3"]["router_if"] = "eth1"                  # r3:eth1 is already L23


def m_unknown_router(s):
    s["links"]["L41"]["b"] = "r5"


def m_cost_zero(s):
    s["links"]["L12"]["ospf_cost"] = 0


def m_not_30(s):
    s["links"]["L12"]["subnet"] = "10.1.12.0/29"


def m_remove_redundancy(s):
    del s["links"]["L41"]                                       # r4 now hangs on one link: no alternate path
    del s["links"]["L34"]


def m_overload(s):
    s["demands"].append({"src": "srv", "dst": "h3", "mbps": 50})   # 90 Mbit/s on L13


def m_dup_router_id(s):
    s["routers"]["r4"]["id"] = 3                                # two routers with router-id 10.0.0.3


def m_ont_port_twice(s):
    s["access"]["onts"]["ont4"]["port"] = 1


def m_ont_port_range(s):
    s["access"]["onts"]["ont4"]["port"] = 40                    # a 1:32 splitter has no port 40


def m_pon_overlaps_customer(s):
    s["access"]["olts"]["olt1"]["pon_subnet"] = "100.64.3.0/24"


def m_wrong_asn(s):
    s["upstreams"]["up1"]["asn"] = 65000                        # eBGP peer configured with our own ASN


MUTATIONS = [
    ("overlapping subnets on two links", m_overlap),
    ("lightpath on a fibre that doesn't exist (typo)", m_unknown_fibre),
    ("lightpath route with a gap", m_broken_lightpath),
    ("lightpath that doesn't reach the link's far end", m_wrong_end),
    ("same router interface used twice", m_duplicate_iface),
    ("link to a router that doesn't exist", m_unknown_router),
    ("OSPF cost 0", m_cost_zero),
    ("core link not a /30", m_not_30),
    ("redundancy removed (a router left on a single link)", m_remove_redundancy),
    ("new demand overloads a link above 80 %", m_overload),
    ("two routers with the same router-id", m_dup_router_id),
    ("two ONTs on the same splitter port", m_ont_port_twice),
    ("ONT on a splitter port that doesn't exist", m_ont_port_range),
    ("PON subnet overlapping a customer LAN", m_pon_overlaps_customer),
    ("eBGP upstream with our own ASN (session would be iBGP)", m_wrong_asn),
]


def gates(s: dict) -> str | None:
    """Run the static gates CI runs before the twin. Return the name of the gate that rejects, or None."""
    try:
        model.validate(s)
        model.routers(s)
    except model.SotError as e:
        return f"SoT validation: {str(e)[:90]}"
    import networkx as nx
    g = whatif.graph(s).to_undirected()
    if list(nx.bridges(g)) or not nx.is_connected(g):
        return "redundancy rule: a core link without an alternate path"
    p = whatif.place_demands(s)
    if p.unreachable:
        return "capacity what-if: unreachable demand"
    hot = [k for k, u in p.util_pct(s["meta"]["capacity_mbps"]).items() if u > s["meta"]["max_utilisation_pct"]]
    if hot:
        return f"capacity what-if: {hot[0][0]} above {s['meta']['max_utilisation_pct']}%"
    return None


def scoreboard() -> list[tuple[str, str | None]]:
    base = model.load()
    assert gates(copy.deepcopy(base)) is None, "the real SoT must pass"
    out = []
    for name, fn in MUTATIONS:
        s = copy.deepcopy(base)
        fn(s)
        out.append((name, gates(s)))
    return out


if __name__ == "__main__":
    rows = scoreboard()
    caught = sum(1 for _, g in rows if g)
    lines = ["# Bad changes: caught before any router saw them", "",
             f"**{caught} / {len(rows)} caught by the static gates** (SoT validation, redundancy rule, capacity what-if). "
             "Generated by `python tests/bad_changes.py`; enforced by `tests/test_bad_changes.py` on every PR.", "",
             "| # | Bad change | Caught by |", "|---|---|---|"]
    lines += [f"| {i} | {n} | {g or '**NOT CAUGHT**'} |" for i, (n, g) in enumerate(rows, 1)]
    text = "\n".join(lines) + "\n"
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "bad-changes.md").write_bytes(text.encode())
    print(text)
